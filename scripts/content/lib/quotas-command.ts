/** pnpm content:quotas: writes content/exam/quotas.yaml from the registry and the blueprint (spec 2.6, 4.3). */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { TASK_IDS } from '../../../schemas/common.ts';
import { Quotas } from '../../../schemas/exam.ts';
import { DOMAIN_IDS } from '../../../schemas/ids.ts';
import {
  domainCounts,
  FORM_COUNT,
  FORM_SIZE,
  MAX_PER_CONCEPT,
  MULTI_PER_FORM,
  multiByModule,
  poolCells,
  taskCounts,
} from '../../../src/engine/quotas.ts';
import { type Context, loadContext, QUOTAS_FILE } from './context.ts';

export const QUOTAS_USAGE = 'usage: pnpm content:quotas [--check]';
export const QUOTAS_HEADER =
  '# Generated by pnpm content:quotas from concepts.yaml and blueprint.yaml; never edit by hand.';

/** The quotas of a context's tested concepts and blueprint weights, checked against the schema. */
export function quotasOf(ctx: Context): Quotas {
  const blueprint = ctx.blueprint;
  if (blueprint === null) throw new Error('content/exam/blueprint.yaml is missing or invalid');
  const concepts = ctx.concepts
    .filter((c) => c.tested !== false)
    .map((c) => ({ id: c.id, module: Number(c.home.slice(1, 3)), tasks: c.tasks }));
  const weight = (d: string): number => blueprint.domains.find((x) => x.id === d)?.weight ?? 0;
  const domains = domainCounts({ '1': weight('1'), '2': weight('2'), '3': weight('3'), '4': weight('4') });
  const tasks = taskCounts(concepts, domains, TASK_IDS);
  const cells = poolCells(concepts, tasks);
  const times = (n: number): number => FORM_COUNT * n;
  return Quotas.parse({
    form: { size: FORM_SIZE, domains, tasks, multi: { ...MULTI_PER_FORM } },
    pool: {
      size: FORM_COUNT * FORM_SIZE,
      forms: FORM_COUNT,
      maxPerConcept: MAX_PER_CONCEPT,
      multi: {
        '1': times(MULTI_PER_FORM['1']),
        '2': times(MULTI_PER_FORM['2']),
        '3': times(MULTI_PER_FORM['3']),
        '4': times(MULTI_PER_FORM['4']),
      },
    },
    cells,
    multiByModule: multiByModule(cells),
  });
}

/** quotas.yaml text: compact flow maps per cell, and task and domain ids quoted so YAML keeps them strings. */
export function quotasText(q: Quotas): string {
  const counts = (record: Readonly<Record<string, number>>, keys: readonly string[]): string =>
    `{ ${keys.map((k) => `"${k}": ${record[k]}`).join(', ')} }`;
  return [
    QUOTAS_HEADER,
    'form:',
    `  size: ${q.form.size}`,
    `  domains: ${counts(q.form.domains, DOMAIN_IDS)}`,
    '  tasks:',
    ...TASK_IDS.map((t) => `    "${t}": ${q.form.tasks[t]}`),
    `  multi: ${counts(q.form.multi, DOMAIN_IDS)}`,
    'pool:',
    `  size: ${q.pool.size}`,
    `  forms: ${q.pool.forms}`,
    `  maxPerConcept: ${q.pool.maxPerConcept}`,
    `  multi: ${counts(q.pool.multi, DOMAIN_IDS)}`,
    'cells:',
    ...q.cells.map((c) => `  - { module: ${c.module}, task: "${c.task}", target: ${c.target} }`),
    'multiByModule:',
    ...q.multiByModule.map((m) => `  - { module: ${m.module}, domain: "${m.domain}", target: ${m.target} }`),
    '',
  ].join('\n');
}

/** The summary lines: the pool size, cells and modules, then each task's per-form and pool count. */
function summary(q: Quotas): string[] {
  const modules = new Set(q.cells.map((c) => c.module)).size;
  return [
    `quotas: ${q.pool.size} items in ${q.cells.length} cells over ${modules} modules`,
    ...TASK_IDS.map((t) => `${t} per form ${q.form.tasks[t]}, pool ${q.pool.forms * q.form.tasks[t]}`),
  ];
}

/** Writes quotas.yaml, or with --check only compares it; exit code 1 on bad arguments, bad sources or a stale file. */
export function runQuotas(root: string, argv: readonly string[]): { code: number; out: string[] } {
  if (argv.some((a) => a !== '--check')) return { code: 1, out: [QUOTAS_USAGE] };
  let quotas: Quotas;
  const ctx = loadContext(root);
  try {
    quotas = quotasOf(ctx);
  } catch (error) {
    return { code: 1, out: [`quotas: ${error instanceof Error ? error.message : String(error)}`] };
  }
  const text = quotasText(quotas);
  if (argv.includes('--check')) {
    if (ctx.read(QUOTAS_FILE) !== text) {
      return { code: 1, out: ['quotas.yaml is out of date; run pnpm content:quotas'] };
    }
    return { code: 0, out: [...summary(quotas), 'quotas.yaml is up to date'] };
  }
  writeFileSync(join(root, QUOTAS_FILE), text);
  return { code: 0, out: summary(quotas) };
}
