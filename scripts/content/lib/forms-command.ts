/**
 * pnpm content:forms (spec 4.3): splits the live exam pool into mock forms A to D with a fixed seed and writes
 * content/exam/forms.yaml; --freeze then freezes the forms in that file, but only when R10's exam quotas and every
 * form hold. Everything it prints is form ids, counts, task, domain and concept ids, module numbers and qids.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { stringify } from 'yaml';
import type { Forms } from '../../../schemas/exam.ts';
import { FORM_IDS } from '../../../schemas/ids.ts';
import { buildForms } from '../../../src/engine/forms.ts';
import { examQuotaProblems } from '../rules/r10-coverage.ts';
import { formSetProblems, formTargets, liveFormItems } from '../rules/r12-forms.ts';
import { type Context, FORMS_FILE, loadContext, POOL_DIR, QUOTAS_FILE } from './context.ts';

export const FORMS_USAGE = 'usage: pnpm content:forms [--seed N] [--freeze [--allow-short-cells]]';
/** The seed of the Phase 3 forms: the Saturday the phase ships. */
export const FORMS_SEED = 20261024;
export const FORMS_HEADER =
  '# Generated by pnpm content:forms from the live exam pool and quotas.yaml; never edit by hand.\n' +
  '# A form with frozen: true never changes again (rule R2); qids only, so this file shows no item text.\n';

type Args = { freeze: false; seed: number } | { freeze: true; allowShortCells: boolean };

function parseArgs(argv: readonly string[]): Args | null {
  let seed: number | null = null;
  let freeze = false;
  let allowShortCells = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--freeze') freeze = true;
    else if (arg === '--allow-short-cells') allowShortCells = true;
    else if (arg === '--seed' && /^\d+$/.test(argv[i + 1] ?? '')) seed = Number(argv[++i]);
    else return null;
  }
  if (freeze) return seed === null ? { freeze, allowShortCells } : null;
  return allowShortCells ? null : { freeze, seed: seed ?? FORMS_SEED };
}

const write = (ctx: Context, forms: Forms): void => {
  writeFileSync(join(ctx.root, FORMS_FILE), FORMS_HEADER + stringify(forms));
};

/** Keeps the frozen forms as they are and builds the others from the live items that sit in no frozen form. */
function build(ctx: Context, seed: number): { code: number; out: string[] } {
  const blocked = (why: string) => ({ code: 1, out: [`forms: blocked: ${why}`] });
  const r1 = ctx.loadErrors.some(
    (f) => f.file === FORMS_FILE || f.file === QUOTAS_FILE || f.file.startsWith(`${POOL_DIR}/`),
  );
  if (r1) return blocked('content/exam/ has R1 findings; run pnpm content:validate');
  if (ctx.quotas === null) return blocked('quotas.yaml is missing; run pnpm content:quotas');
  const frozen = (ctx.forms?.forms ?? []).filter((f) => f.frozen);
  const inFrozen = new Set(frozen.flatMap((f) => f.qids));
  const open = FORM_IDS.filter((id) => !frozen.some((f) => f.id === id));
  let built: string[][] = [];
  if (open.length > 0) {
    const items = [...liveFormItems(ctx).values()].filter((i) => !inFrozen.has(i.id));
    const result = buildForms({ items, targets: formTargets(ctx.quotas), count: open.length, seed });
    if (!result.ok) return blocked(result.blocker);
    built = result.forms;
  }
  const forms: Forms = {
    seed,
    forms: FORM_IDS.map(
      (id) => frozen.find((f) => f.id === id) ?? { id, frozen: false, qids: built[open.indexOf(id)] ?? [] },
    ),
  };
  write(ctx, forms);
  return {
    code: 0,
    out: [`forms: ${forms.forms.map((f) => `${f.id} ${f.qids.length}`).join(', ')} (seed ${seed})`],
  };
}

/** Freezes the forms in forms.yaml as they are, after R10's exam quotas and R12's form checks pass. */
function freeze(ctx: Context, allowShortCells: boolean): { code: number; out: string[] } {
  const refused = (why: string) => ({ code: 1, out: [`freeze refused: ${why}`] });
  if (ctx.forms === null) return refused('forms.yaml is missing; run pnpm content:forms');
  if (ctx.quotas === null) return refused('quotas.yaml is missing; run pnpm content:quotas');
  const quota = examQuotaProblems(ctx).map((f) => f.message);
  const form = formSetProblems(ctx.forms, liveFormItems(ctx), formTargets(ctx.quotas));
  if (form.length > 0 || (quota.length > 0 && !allowShortCells)) {
    return {
      code: 1,
      out: [
        `freeze refused: ${quota.length} quota problems, ${form.length} form problems`,
        ...quota,
        ...form,
      ],
    };
  }
  write(ctx, { ...ctx.forms, forms: ctx.forms.forms.map((f) => ({ ...f, frozen: true })) });
  return { code: 0, out: [...quota.map((m) => `allowed: ${m}`), `frozen: ${FORM_IDS.join(', ')}`] };
}

export function runForms(root: string, argv: readonly string[]): { code: number; out: string[] } {
  const args = parseArgs(argv);
  if (args === null) return { code: 1, out: [FORMS_USAGE] };
  const ctx = loadContext(root);
  return args.freeze ? freeze(ctx, args.allowShortCells) : build(ctx, args.seed);
}
