/**
 * Seeded randomness for the engine: the same seed always gives the same order,
 * so a resumed session or a replay shows the same questions in the same order.
 * The app draws session seeds with `crypto.getRandomValues` outside the engine.
 */

/** A small fast PRNG; each call returns a value in [0, 1). */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 32-bit FNV-1a over UTF-16 code units, unsigned. */
export function fnv1a(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** Fisher-Yates on a copy; the input stays as it was. */
export function shuffle<T>(items: readonly T[], random: () => number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    const a = out[i] as T;
    out[i] = out[j] as T;
    out[j] = a;
  }
  return out;
}

/** The seed for one question inside a session, so each question shuffles on its own. */
export function seedFor(sessionSeed: number, qid: string): number {
  return (sessionSeed ^ fnv1a(qid)) >>> 0;
}
