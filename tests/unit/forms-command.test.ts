import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { parse, stringify } from 'yaml';
import { Forms } from '../../schemas/exam.ts';
import { FORMS_FILE, loadContext } from '../../scripts/content/lib/context.ts';
import { FORMS_SEED, FORMS_USAGE, runForms } from '../../scripts/content/lib/forms-command.ts';
import { r12 } from '../../scripts/content/rules/r12-forms.ts';
import { FIXTURE_TODAY, makeFixtureRoot } from '../fixtures/content-root.ts';
import { writeExamPool } from '../fixtures/exam-pool.ts';
import { POOL_FILE } from '../fixtures/questions.ts';

const formsOf = (root: string): Forms => Forms.parse(parse(readFileSync(join(root, FORMS_FILE), 'utf8')));
/** Drops the last qid of form A, as a hand edit would. */
function dropFromFormA(root: string): void {
  const forms = formsOf(root);
  forms.forms[0]?.qids.pop();
  writeFileSync(join(root, FORMS_FILE), stringify(forms));
}

describe('pnpm content:forms', () => {
  it('writes four forms of 65 that pass R12, and the same file on a second run', () => {
    const root = makeFixtureRoot();
    writeExamPool(root);
    expect(runForms(root, [])).toEqual({ code: 0, out: ['forms: A 65, B 65, C 65, D 65 (seed 20261024)'] });
    const first = readFileSync(join(root, FORMS_FILE), 'utf8');
    expect(first.startsWith('# Generated by pnpm content:forms')).toBe(true);
    const forms = formsOf(root);
    expect(forms.seed).toBe(FORMS_SEED);
    expect(forms.forms.map((f) => [f.id, f.frozen, f.qids.length])).toEqual([
      ['A', false, 65],
      ['B', false, 65],
      ['C', false, 65],
      ['D', false, 65],
    ]);
    expect(r12.run(loadContext(root, { today: FIXTURE_TODAY }))).toEqual([]);
    expect(runForms(root, []).code).toBe(0);
    expect(readFileSync(join(root, FORMS_FILE), 'utf8')).toBe(first);
  });

  it('names the task that blocks a pool one item short, and writes nothing', () => {
    const root = makeFixtureRoot();
    const questions = writeExamPool(root);
    const last = questions.filter((q) => q.task === '4.2').at(-1)?.id ?? '';
    const text = readFileSync(join(root, POOL_FILE), 'utf8');
    const at = text.indexOf(`id: ${last}`);
    writeFileSync(
      join(root, POOL_FILE),
      text.slice(0, at) + text.slice(at).replace('status: live', 'status: draft'),
    );
    expect(runForms(root, [])).toEqual({
      code: 1,
      out: ['forms: blocked: task 4.2 has 3 live items; 4 forms need 4'],
    });
    expect(loadContext(root, { today: FIXTURE_TODAY }).forms).toBeNull();
  });

  it('refuses to freeze while a quota cell is short', () => {
    const root = makeFixtureRoot();
    writeExamPool(root, { splitTask: '4.2' });
    expect(runForms(root, []).code).toBe(0);
    expect(runForms(root, ['--freeze'])).toEqual({
      code: 1,
      out: [
        'freeze refused: 1 quota problems, 0 form problems',
        'cell m02 task 4.2 has 0 live exam items; it needs 2',
      ],
    });
    expect(formsOf(root).forms.map((f) => f.frozen)).toEqual([false, false, false, false]);
  });

  it('freezes every form of a pool that meets its quotas', () => {
    const root = makeFixtureRoot();
    writeExamPool(root);
    runForms(root, []);
    const built = formsOf(root);
    expect(runForms(root, ['--freeze'])).toEqual({ code: 0, out: ['frozen: A, B, C, D'] });
    const frozen = formsOf(root);
    expect(frozen.forms.map((f) => f.frozen)).toEqual([true, true, true, true]);
    expect(frozen.forms.map((f) => f.qids)).toEqual(built.forms.map((f) => f.qids));
    expect(runForms(root, []).out).toEqual(['forms: A 65, B 65, C 65, D 65 (seed 20261024)']);
    expect(formsOf(root)).toEqual(frozen);
  });

  it('freezes a pool with a short cell only with --allow-short-cells, and never a form with a problem', () => {
    const root = makeFixtureRoot();
    writeExamPool(root, { splitTask: '4.2' });
    runForms(root, []);
    dropFromFormA(root);
    const refused = runForms(root, ['--freeze', '--allow-short-cells']);
    expect(refused.code).toBe(1);
    expect(refused.out[0]).toMatch(/^freeze refused: 1 quota problems, [1-9]\d* form problems$/);
    expect(refused.out).toContain('form A has 64 items; it needs 65');
    expect(formsOf(root).forms.map((f) => f.frozen)).toEqual([false, false, false, false]);

    runForms(root, ['--seed', String(FORMS_SEED)]);
    expect(runForms(root, ['--freeze', '--allow-short-cells'])).toEqual({
      code: 0,
      out: ['allowed: cell m02 task 4.2 has 0 live exam items; it needs 2', 'frozen: A, B, C, D'],
    });
  });

  it('prints its usage for an unknown flag, --allow-short-cells without --freeze, or --seed with --freeze', () => {
    const root = makeFixtureRoot();
    for (const argv of [
      ['--frozen'],
      ['--allow-short-cells'],
      ['--freeze', '--seed', '7'],
      ['--seed', 'x'],
    ]) {
      expect(runForms(root, argv)).toEqual({ code: 1, out: [FORMS_USAGE] });
    }
    expect(FORMS_USAGE).toBe('usage: pnpm content:forms [--seed N] [--freeze [--allow-short-cells]]');
  });

  it('is blocked without quotas.yaml and refuses to freeze without forms.yaml', () => {
    const root = makeFixtureRoot();
    expect(runForms(root, [])).toEqual({
      code: 1,
      out: ['forms: blocked: quotas.yaml is missing; run pnpm content:quotas'],
    });
    writeExamPool(root);
    expect(runForms(root, ['--freeze'])).toEqual({
      code: 1,
      out: ['freeze refused: forms.yaml is missing; run pnpm content:forms'],
    });
  });
});
