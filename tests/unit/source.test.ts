import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { FingerprintFile } from '../../schemas/fingerprint.ts';
import { runsAgainst, unpack } from '../../scripts/content/lib/fingerprint.ts';
import { allowFile, fingerprintCourse } from '../../scripts/content/lib/fingerprint-files.ts';
import { sourceTitles, splitItems } from '../../scripts/content/lib/source.ts';
import { words } from '../../scripts/content/lib/text.ts';

const source = readFileSync(
  fileURLToPath(new URL('../fixtures/source/module-01.md', import.meta.url)),
  'utf8',
);

describe('splitItems', () => {
  it('cuts each knowledge check and assessment item at the next block or heading', () => {
    const items = splitItems(source);
    expect(items.map((i) => i.id)).toEqual(['kc-01', 'quiz-01']);
    expect(items[0]?.text).toBe(
      [
        'Which feature lets a branch borrow ovens only during the busy morning hours?',
        '- (CORRECT) Renting ovens from the shared kitchen by the minute',
        '- (wrong) Buying a second oven for every branch',
      ].join('\n'),
    );
    expect(items[1]?.text).toContain('Sign a ten year cabinet lease');
    expect(items[1]?.text).not.toContain('ASSESSMENT');
  });
});

describe('sourceTitles', () => {
  it('lists lesson titles, then the module title in full and without its prefix', () => {
    expect(sourceTitles(source)).toEqual([
      'What a Bakery Cloud Is',
      'Assessment',
      'Module 1: Baking Basics',
      'Baking Basics',
    ]);
  });
});

const fingerprintModule = (module: number, text: string) => {
  const [file] = fingerprintCourse(new Map([[module, text]]));
  if (file === undefined) throw new Error('no fingerprint file');
  return file;
};

describe('fingerprintCourse on one module', () => {
  it('fingerprints the text and the items in two sets, lists the item ids, and finds a copied run', () => {
    const file = fingerprintModule(1, source);
    expect(FingerprintFile.parse(file)).toEqual(file);
    expect(file.itemIds).toEqual(['kc-01', 'quiz-01']);
    const copied = words(
      'Bakers rent proofing cabinets by the minute and hand them back once the dough has risen',
    );
    expect(runsAgainst(copied, [unpack(file.text), unpack(file.items)])).toHaveLength(1);
  });

  const block = (marker: string): string => `${marker}\nWhich oven should a branch rent this morning?\n`;

  it('sorts the item ids whatever order the source holds them in', () => {
    const shuffled = [
      '[ASSESSMENT Q2 (MULTIPLE_CHOICE)]',
      '[KNOWLEDGE CHECK]',
      '[ASSESSMENT Q1 (MULTIPLE_CHOICE)]',
    ]
      .map(block)
      .join('\n');
    expect(fingerprintModule(1, shuffled).itemIds).toEqual(['kc-01', 'quiz-01', 'quiz-02']);
  });

  it('refuses a source that repeats an assessment question number', () => {
    const repeated = ['[ASSESSMENT Q1 (MULTIPLE_CHOICE)]', '[ASSESSMENT Q1 (MULTIPLE_CHOICE)]']
      .map(block)
      .join('\n');
    expect(() => fingerprintModule(1, repeated)).toThrow('module 1 repeats item quiz-01');
  });
});

describe('allowFile', () => {
  it('writes a generated header, the titles, then the pipeline phrases', () => {
    expect(allowFile([source], '# comment\nOperational excellence, security\n').split('\n')).toEqual([
      '# Generated by pnpm content:fingerprint from the course source; do not edit.',
      'What a Bakery Cloud Is',
      'Assessment',
      'Module 1: Baking Basics',
      'Baking Basics',
      'Operational excellence, security',
      '',
    ]);
  });
});
